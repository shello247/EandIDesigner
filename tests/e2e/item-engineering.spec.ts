async function pasteSnippet(page: Page) {
  await page.context().grantPermissions(["clipboard-read", "clipboard-write"]);
  const clipboardImage = await page.evaluate(async () => {
    const canvas = document.createElement("canvas"); canvas.width = 180; canvas.height = 80;
    const context = canvas.getContext("2d")!;
    context.fillStyle = "#e6f6f4"; context.fillRect(0, 0, canvas.width, canvas.height);
    context.fillStyle = "#006d70"; context.font = "bold 16px sans-serif"; context.fillText("Wiring snippet", 16, 45);
    const image = await new Promise<Blob>(resolve => canvas.toBlob(blob => resolve(blob!), "image/png"));
    await navigator.clipboard.write([new ClipboardItem({ "image/png": image })]);
    const savedImage = await (await navigator.clipboard.read())[0].getType("image/png");
    return new Promise<string>(resolve => {
      const reader = new FileReader(); reader.onload = () => resolve(reader.result as string); reader.readAsDataURL(savedImage);
    });
  });
  await page.getByRole("region", { name: "New engineer note", exact: true }).getByRole("group", { name: "Paste snippet image", exact: true }).click();
  await page.keyboard.press("Control+v");
  return clipboardImage;
}


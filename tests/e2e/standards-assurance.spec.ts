test("draft cancellation, concurrent revision conflict and historical view", async ({ page, context }) => {
  const title = "QA Concurrent " + randomUUID().slice(0, 8);
  await page.goto("/standards");
  await page.getByRole("button", { name: "Profiles & History", exact: true }).click();
  await page.getByRole("button", { name: "Add profile", exact: true }).click();
  let dialog = page.getByRole("dialog", { name: "Add profile", exact: true });
  await dialog.getByLabel("Title", { exact: true }).fill(title);
  await dialog.getByRole("button", { name: "Save revision" }).click();
  await expect(dialog.getByRole("alert")).toBeVisible();
  await expect(dialog.getByLabel("Title", { exact: true })).toHaveValue(title);
  page.once("dialog", event => event.dismiss());
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(dialog).toBeVisible();
  await dialog.getByLabel("Purpose", { exact: true }).fill("Concurrency verification");
  await dialog.getByLabel("Scope", { exact: true }).fill("Synthetic empty profile");
  await dialog.getByRole("button", { name: "Save revision" }).click();
  await expect(dialog).toBeHidden();
  await page.getByRole("link", { name: title, exact: true }).click();
  await expect(page.getByRole("heading", { name: "Scoped coverage", exact: true })).toBeVisible();
  const second = await context.newPage();
  await second.goto(page.url());
  await second.getByRole("button", { name: "Edit current revision" }).click();
  await second.getByLabel("Title", { exact: true }).fill(title + " stale edit");
  await page.getByRole("button", { name: "Edit current revision" }).click();
  dialog = page.getByRole("dialog", { name: "Edit profile", exact: true });
  await dialog.getByLabel("Title", { exact: true }).fill(title + " saved edit");
  await dialog.getByRole("button", { name: "Save revision" }).click();
  await expect(dialog).toBeHidden();
  await second.getByRole("button", { name: "Save revision" }).click();
  await expect(second.getByRole("dialog").getByRole("alert")).toContainText("newer revision");
  await expect(second.getByLabel("Title", { exact: true })).toHaveValue(title + " stale edit");
  second.once("dialog", event => event.accept());
  await second.getByRole("dialog").press("Escape");
  await expect(second.getByRole("dialog")).toBeHidden();
  await second.close();
  await page.getByRole("button", { name: /^R1 ·/ }).click();
  await expect(page.getByText("Historical revision", { exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: title, exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Edit current revision" })).toBeDisabled();
});

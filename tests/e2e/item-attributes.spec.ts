test("row save in flight retains later edits and failure retains the draft", async ({ page }) => {
  const item = await fixture(page); const dialog = await add(page);
  await dialog.getByLabel("Value", { exact: true }).fill("10");
  let release!: () => void; const hold = new Promise<void>(resolve => { release = resolve; });
  await page.route("**/bom/items/" + item.id, async route => { if (route.request().method() === "POST") await hold; await route.continue(); });
  await dialog.getByRole("button", { name: "Save Attribute", exact: true }).click();
  await expect(dialog.getByRole("button", { name: "Saving…", exact: true })).toBeDisabled();
  await dialog.getByLabel("Value", { exact: true }).fill("12");
  await dialog.getByLabel("Group title").fill("Later group title");
  release();
  await expect(dialog.getByText("Submitted values saved.", { exact: false })).toBeVisible();
  await expect(dialog.getByLabel("Value", { exact: true })).toHaveValue("12");
  await expect(dialog.getByLabel("Group title")).toHaveValue("Later group title");
  await expect(dialog.getByLabel("Specification group")).toHaveValue("new");
  await page.unrouteAll();
  await page.route("**/bom/items/" + item.id, async route => { if (route.request().method() === "POST") await route.abort("failed"); else await route.continue(); });
  await dialog.getByRole("button", { name: "Save Attribute", exact: true }).click();
  await expect(dialog.getByRole("alert")).toBeVisible();
  await expect(dialog.getByLabel("Value", { exact: true })).toHaveValue("12");
  const saved = await prisma.bomItemEngineeringRevision.findFirstOrThrow({ where: { itemId: item.id }, orderBy: { revisionNumber: "desc" } });
  expect(JSON.parse(saved.profileJson).entries[0].payload.value).toBe(10);
});

test("power-supply input and output values are saved independently", async ({ page }) => {
  const item = await fixture(page, "power_supply");
  for (const [context, value] of [["supply_input", "240"], ["supply_output", "24"]]) {
    const dialog = await add(page, "Nominal voltage", "attribute_type_nominal_voltage_v1");
    await dialog.getByLabel("Value", { exact: true }).fill(value);
    if (context === "supply_output") {
      await dialog.getByText("Conditions & Source", { exact: true }).click();
      await dialog.getByLabel("Specification group").selectOption("new");
    }
    await dialog.getByLabel("Group title").fill(context);
    await dialog.getByLabel("Specification context").selectOption(context);
    await dialog.getByRole("button", { name: "Save Attribute", exact: true }).click();
    await expect(dialog).toHaveCount(0);
  }
  const revision = await prisma.bomItemEngineeringRevision.findFirstOrThrow({ where: { itemId: item.id }, orderBy: { revisionNumber: "desc" } });
  const profile = JSON.parse(revision.profileJson);
  expect(profile.groups.map((group: { context: string }) => group.context)).toEqual(["supply_input", "supply_output"]);
  expect(profile.entries.map((entry: { payload: { value: number } }) => entry.payload.value)).toEqual([240, 24]);
});
